package app.src.main.java.app.model;

import java.time.LocalDate;

public class Game {
    private int gameId;
    private String gameTitle;
    private String description;
    private String genre;
    private String publisher;
    private LocalDate releaseDate;
    private boolean archived;

    // constructor for games already in the database
    public Game(int gameId, String gameTitle, String description, String genre, String publisher, LocalDate releaseDate, boolean archived) {
        this.gameId = gameId;
        this.gameTitle = gameTitle;
        this.description = description;
        this.genre = genre;
        this.publisher = publisher;
        this.releaseDate = releaseDate;
        this.archived = archived;
    }

    // constructor for a new game (id generated by sqlite)
    public Game(String gameTitle, String description, String genre, String publisher, LocalDate releaseDate, boolean archived) {
        this(0, gameTitle, description, genre, publisher, releaseDate, archived);
    }

    public int getGameId() {
        return gameId;
    }

    public void setGameId(int gameId) {
        this.gameId = gameId;
    }

    public String getGameTitle() {
        return gameTitle;
    }

    public void setGameTitle(String gameTitle) {
        this.gameTitle = gameTitle;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getGenre() {
        return genre;
    }

    public void setGenre(String genre) {
        this.genre = genre;
    }

    public String getPublisher() {
        return publisher;
    }

    public void setPublisher(String publisher) {
        this.publisher = publisher;
    }

    public LocalDate getReleaseDate() {
        return releaseDate;
    }

    public void setReleaseDate(LocalDate releaseDate) {
        this.releaseDate = releaseDate;
    }

    public boolean isArchived() {
        return archived;
    }

    public void setArchived(boolean archived) {
        this.archived = archived;
    }
}